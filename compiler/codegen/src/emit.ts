// Emits an LLVM IR module for an Ore module: the layers of ModuleEmitter put together.
import * as ir from "@ore/ir"
import { inlineCalls, planStack } from "@ore/opt"
import { globalName, sizeOf } from "./ll"
import { type EmitOptions, STR, FN, IFACE, FRAME, ARRAY, MAP } from "./context"
import { findGlobals } from "./helpers"
import { JsonEmitter } from "./json"

export type { EmitOptions } from "./context"

/**
 * Emits an LLVM IR module for an Ore module. The runtime, written in Ore
 * (runtime/core), is part of the module, so its functions inline into the
 * program's code.
 */
export function emitModule(module: ir.Module, options: EmitOptions = { debug: false }): string {
  // Inlining loses the frames of stack traces, so debug builds keep every call.
  if (!options.debug) inlineCalls(module)
  return new ModuleEmitter(module, options).emit()
}

export class ModuleEmitter extends JsonEmitter {
  emit(): string {
    const m = this.module
    this.file = m.file
    this.defs.set(STR, `${STR} = type { ptr, i64 }`)
    this.defs.set(FN, `${FN} = type { ptr, ptr }`)
    this.defs.set(IFACE, `${IFACE} = type { ptr, ptr }`)
    this.defs.set(FRAME, `${FRAME} = type { ptr, ptr, ptr, i32 }`)
    this.defs.set(ARRAY, `${ARRAY} = type { ptr, i64, i64 }`)
    this.defs.set(MAP, `${MAP} = type { i64, i64, i64, ptr, ptr, ptr, i64, i64, i64, ptr, i64 }`)
    this.decls.set("@ore_rt_top", "@ore_rt_top = external thread_local global ptr")
    this.decls.set("@llvm.threadlocal.address.p0", "declare ptr @llvm.threadlocal.address.p0(ptr)")
    this.plan = planStack(m)
    for (const func of m.functions) if (func.attributes?.runtime) this.runtime.set(func.attributes.runtime, func)
    const roots: string[] = []
    for (const local of findGlobals(m)) {
      this.globals.add(local)
      // The collector scans the globals that may hold pointers; a thread-local one belongs to its thread.
      if (!local.threadLocal && !["int", "float", "bool"].includes(local.type.kind)) {
        roots.push(`{ ptr, i64 } { ptr ${this.globalOf(local)}, i64 ${sizeOf(this.mt(local.type))} }`)
      }
      // An exported global is the definition of a C name, such as the runtime's `ore_rt_top`.
      if (local.exportName) this.decls.delete(`@${local.exportName}`)
      const linkage = local.exportName ? "" : "internal "
      this.out.push(`${this.globalOf(local)} = ${linkage}${local.threadLocal ? "thread_local " : ""}global ${this.mt(local.type)} zeroinitializer`)
    }
    for (const itab of m.itabs) this.out.push(this.itab(itab))
    for (const func of m.functions) {
      if (func.extern) {
        this.declareExtern(func)
        continue
      }
      this.out.push(this.function(func, false))
      if (this.plan.ctorsAt.has(func)) this.out.push(this.function(func, true))
    }
    const inits = m.inits.map((f) => `  call void ${globalName(f.name)}()`)
    this.out.push(["define void @ore_entry() {", ...inits, "  ret void", "}"].join("\n"))
    // The runtime declares ore_entry to take its address; the definition is here.
    this.decls.delete("@ore_entry")
    // The table of globals for the collector's roots, read through two functions the runtime declares.
    this.out.push(`@ore.globals = internal constant [${roots.length} x { ptr, i64 }] [${roots.join(", ")}]`)
    this.out.push("define ptr @ore_globals_table() {\n  ret ptr @ore.globals\n}")
    this.out.push(`define i64 @ore_globals_count() {\n  ret i64 ${roots.length}\n}`)
    this.decls.delete("@ore_globals_table")
    this.decls.delete("@ore_globals_count")
    return [
      "; Generated by the Ore compiler. Do not edit.",
      ...this.defs.values(),
      ...this.decls.values(),
      ...this.strings.values(),
      "",
      ...this.helpers.values(),
      "",
      ...this.out,
      "",
    ].join("\n")
  }
}
