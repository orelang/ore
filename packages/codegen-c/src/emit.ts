// Expressions (always fully parenthesized)

const cCompare: Record<ir.CompareOp, string> = { "===": "==", "!==": "!=", "<": "<", "<=": "<=", ">": ">", ">=": ">=" }

function emitExpr(expr: ir.Expr): string {
  if ((expr as unknown as Raw).k === "raw") return (expr as unknown as Raw).code
  switch (expr.k) {
    case "int":
      return intLiteral(expr.type, expr.value)
    case "float":
      return floatLiteral(expr.type, expr.value)
    case "bool":
      return expr.value ? "true" : "false"
    case "string":
      return `ORE_STR(${stringLiteral(expr.value)})`
    case "local":
      return access(expr.local)
    case "assign":
      return emitAssign(expr)
    case "incdec": {
      if (expr.target.k === "local") {
        const name = access(expr.target.local)
        return expr.prefix ? `(${expr.op}${name})` : `(${name}${expr.op})`
      }
      const p = temp()
      const place = placePointer(expr.target, expr.type, p)
      return `({ ${place} ${expr.prefix ? `${expr.op}(*${p})` : `(*${p})${expr.op}`}; })`
    }
    case "arith":
      return emitArith(expr)
    case "compare":
      return inOrder([expr.left, expr.right], ([l, r]) => {
        if (expr.left.type.kind === "string" && expr.op !== "===" && expr.op !== "!==") return `(ore_rt_str_cmp(${l}, ${r}) ${expr.op} 0)`
        // Interface values are equal when they refer to the same object.
        if (expr.left.type.kind === "interface") return `((${l}).data ${cCompare[expr.op]} (${r}).data)`
        if (expr.left.type.kind === "func") {
          const eq = equals(`(${l})`, `(${r})`, expr.left.type)
          return expr.op === "===" ? eq : `(!${eq})`
        }
        if (isStringLike(expr.left.type)) {
          const eq = `ore_rt_str_eq(${l}, ${r})`
          return expr.op === "===" ? eq : `(!${eq})`
        }
        if (expr.left.type.kind === "union") {
          const u = expr.left.type
          const repr = unionRepr(u)
          const eq = repr.k === "tagged" ? `${unionName(u)}_eq(${l}, ${r})` : equals(`(${l})`, `(${r})`, repr.k === "strings" ? types.string : repr.base)
          return expr.op === "===" ? eq : `(!${eq})`
        }
        return `(${l} ${cCompare[expr.op]} ${r})`
      })
    case "logical":
      return `(${emitExpr(expr.left)} ${expr.op} ${emitExpr(expr.right)})`
    case "unary":
      return expr.type.kind === "float" ? `(${expr.op}${emitExpr(expr.operand)})` : `((${expr.type.name})${expr.op}${emitExpr(expr.operand)})`
    case "not":
      return `(!${emitExpr(expr.operand)})`
    case "convert":
      return emitConvert(expr)
    case "call":
      return inOrder(expr.args, (args) => `${expr.func.name}(${args.join(", ")})`)
    case "builtin":
      return emitBuiltin(expr)
    case "cond":
      return `(${emitExpr(expr.cond)} ? ${emitExpr(expr.then)} : ${emitExpr(expr.else)})`
    case "concat":
      if (expr.parts.length === 0) return `ORE_STR("")`
      if (expr.parts.length === 1) return toString(expr.parts[0]!)
      return inOrder(expr.parts, (parts) => {
        const strings = parts.map((code, i) => toString(raw(code, expr.parts[i]!.type)))
        return `ore_rt_str_concat(${parts.length}, (ore_string[]){${strings.join(", ")}})`
      })
    case "index":
      return inOrder([expr.target, expr.index], ([target, index]) => {
        if (expr.target.type.kind === "string") return `ore_rt_str_at(${target}, (i64)${index})`
        return `(*(${cType(expr.type)} *)ore_rt_array_at(${target}, (i64)${index}, sizeof(${cType(expr.type)})))`
      })
    case "len":
      return expr.value.type.kind === "string" ? `(${emitExpr(expr.value)}).len` : `(${emitExpr(expr.value)})->len`
    case "slice": {
      const parts = [expr.value, ...(expr.start ? [expr.start] : []), ...(expr.end ? [expr.end] : [])]
      return inOrder(parts, ([value, start, end]) => {
        const s = start ? `(i64)${start}` : "0"
        const e = end ? `(i64)${end}` : "ORE_SLICE_END"
        if (expr.type.kind === "string") return `ore_rt_str_slice(${value}, ${s}, ${e})`
        return `ore_rt_array_slice(${value}, sizeof(${cType((expr.type as ir.ArrayType).elem)}), ${s}, ${e})`
      })
    }
    case "array": {
      const elem = cType(expr.type.elem)
      if (expr.elems.length === 0) return `ore_rt_array_new(sizeof(${elem}), 0)`
      const a = temp()
      const d = temp()
      const stores = expr.elems.map((e, i) => `${d}[${i}] = ${emitExpr(e)};`).join(" ")
      return `({ ore_array *${a} = ore_rt_array_new(sizeof(${elem}), ${expr.elems.length}); ${elem} *${d} = (${elem} *)${a}->data; ${stores} ${a}; })`
    }
    case "push": {
      // Evaluate the array and all values before appending, as JavaScript does.
      const elem = cType((expr.array.type as ir.ArrayType).elem)
      const a = temp()
      const values = expr.values.map((v) => [temp(), emitExpr(v)] as const)
      const decls = values.map(([t, v]) => `${elem} ${t} = ${v};`).join(" ")
      const pushes = values.map(([t]) => `*(${elem} *)ore_rt_array_push(${a}, sizeof(${elem})) = ${t};`).join(" ")
      return `({ ore_array *${a} = ${emitExpr(expr.array)}; ${decls} ${pushes} ${a}->len; })`
    }
    case "pop":
      return `(*(${cType(expr.type)} *)ore_rt_array_pop(${emitExpr(expr.array)}, sizeof(${cType(expr.type)})))`
    case "object": {
      const s = structName(expr.type)
      const o = temp()
      const stores = expr.fields.map((f) => `${o}->${fieldName(f.name)} = ${emitExpr(f.value)};`).join(" ")
      return `({ ${s} *${o} = ore_rt_alloc(sizeof(${s})); ${stores} ${o}; })`
    }
    case "field":
      return `(${emitExpr(expr.object)})->${fieldName(expr.name)}`
    case "alloc":
      return `((${structName(expr.type)} *)ore_rt_alloc(sizeof(${structName(expr.type)})))`
    case "method-call":
      return inOrder([expr.receiver, ...expr.args], (args) => `${expr.func.name}(${args.join(", ")})`)
    case "to-iface": {
      if (expr.itab) return `((ore_iface){(void *)${emitExpr(expr.value)}, ore_itab_${expr.itab.id}})`
      const indices = expr.indices!
      if (indices.length === 0) return `ore_rt_iface_project(${emitExpr(expr.value)}, 0, 0)`
      return `ore_rt_iface_project(${emitExpr(expr.value)}, ${indices.length}, (const i32[]){${indices.join(", ")}})`
    }
    case "iface-field":
      return `(*(${cType(expr.type)} *)ore_iface_field(${emitExpr(expr.value)}, ${expr.index}))`
    case "null":
      return inject(expr.type, expr.type.members.findIndex((m) => m.kind === "null"), "")
    case "recast":
      return recast(emitExpr(expr.value), expr.value.type, expr.type)
    case "is-null": {
      const t = temp()
      return `({ ${cType(expr.value.type)} ${t} = ${emitExpr(expr.value)}; ${isNullValue(expr.value.type as UnionType, t)}; })`
    }
    case "optional": {
      // `value?.body`: null when value is null, else body with the value bound.
      const from = expr.value.type as UnionType
      const t = temp()
      const bind = declare(expr.binding, recast(t, from, expr.binding.type))
      if (expr.type.kind !== "union") {
        return `({ ${cType(from)} ${t} = ${emitExpr(expr.value)}; if (!${isNullValue(from, t)}) { ${bind} ${emitExpr(expr.body)}; } })`
      }
      const r = temp()
      const none = inject(expr.type, expr.type.members.findIndex((m) => m.kind === "null"), "")
      return `({ ${cType(from)} ${t} = ${emitExpr(expr.value)}; ${cType(expr.type)} ${r}; if (${isNullValue(from, t)}) ${r} = ${none}; else { ${bind} ${r} = ${emitExpr(expr.body)}; } ${r}; })`
    }
    case "union-field": {
      const u = expr.value.type as UnionType
      const t = temp()
      const r = temp()
      const branches = u.members.map((m, i) => {
        const object = payload(u, t, i)
        let read: string
        let type: Type
        if (m.kind === "struct") {
          type = ir.findField(m, expr.name)!.type
          read = `(${object})->${fieldName(expr.name)}`
        } else {
          const index = (m as ir.InterfaceType).members.findIndex((x) => x.name === expr.name)
          type = (m as ir.InterfaceType).members[index]!.type
          read = `(*(${cType(type)} *)ore_iface_field(${object}, ${index}))`
        }
        return `if (${slotTest(u, t, i)}) ${r} = ${recast(read, type, expr.type)};`
      })
      return `({ ${cType(u)} ${t} = ${emitExpr(expr.value)}; ${cType(expr.type)} ${r}; ${branches.join(" else ")} ${r}; })`
    }
    case "typeof": {
      const from = expr.value.type
      if (from.kind !== "union") return `({ ${emitExpr(expr.value)}; ORE_STR(${stringLiteral(typeofName(from))}); })`
      const t = temp()
      const branches = from.members.map((m, i) => `${slotTest(from, t, i)} ? ORE_STR(${stringLiteral(typeofName(m))}) :`)
      return `({ ${cType(from)} ${t} = ${emitExpr(expr.value)}; ${branches.join(" ")} ORE_STR("object"); })`
    }
    case "is": {
      const t = temp()
      const value = `${cType(expr.value.type)} ${t} = ${emitExpr(expr.value)};`
      if (expr.value.type.kind === "interface") return `({ ${value} ore_iface_is(${t}, ${typeId(expr.member as ir.StructType)}); })`
      const u = expr.value.type as UnionType
      if (!expr.via) return `({ ${value} ${slotTest(u, t, memberIndex(u, expr.member))}; })`
      const i = memberIndex(u, expr.via)
      return `({ ${value} ${slotTest(u, t, i)} && ore_iface_is(${payload(u, t, i)}, ${typeId(expr.member as ir.StructType)}); })`
    }
    case "downcast": {
      const t = temp()
      const message = stringLiteral(`value is not a ${expr.type.name}`)
      return `({ ore_iface ${t} = ${emitExpr(expr.value)}; if (!ore_iface_is(${t}, ${typeId(expr.type)})) ore_rt_panic_cstr(${message}); (${cType(expr.type)})${t}.data; })`
    }
    case "map":
      return emitMapOp(expr)
    case "func-ref":
      return `((ore_closure){(void *)${thunk(expr.func)}, 0})`
    case "closure": {
      const captures = expr.func.captures ?? []
      if (captures.length === 0) return `((ore_closure){(void *)${expr.func.name}, 0})`
      const e = temp()
      const env = envName(expr.func)
      const stores = captures.map((c) => `${e}->c${c.id} = ${boxed(c) ? boxOf(c) : access(c)};`).join(" ")
      return `({ ${env} *${e} = ore_rt_alloc(sizeof(${env})); ${stores} (ore_closure){(void *)${expr.func.name}, ${e}}; })`
    }
    case "call-value": {
      // The callee is evaluated before the arguments.
      const f = temp()
      const type = expr.callee.type as ir.FuncType
      const fn = `(${cType(type.result)} (*)(${["void *", ...type.params.map(cType)].join(", ")}))${f}.fn`
      return `({ ore_closure ${f} = ${emitExpr(expr.callee)}; ${inOrder(expr.args, (args) => `(${fn})(${[`${f}.env`, ...args].join(", ")})`)}; })`
    }
    case "bound-method":
      return emitBound(expr)
    case "array-method":
      return emitArrayMethod(expr)
    case "string-method":
      return inOrder([expr.value, ...expr.args], ([s, ...a]) => stringMethod(expr.method, s!, a))
    case "coalesce": {
      const from = expr.value.type as UnionType
      const t = temp()
      return `({ ${cType(from)} ${t} = ${emitExpr(expr.value)}; ${isNullValue(from, t)} ? ${emitExpr(expr.fallback)} : ${recast(t, from, expr.type)}; })`
    }
    case "iface-call": {
      // The receiver is evaluated once, before the arguments.
      const r = temp()
      const fn = `(${cType(expr.method.result)} (*)(${["void *", ...expr.method.params.map(cType)].join(", ")}))${r}.itab[${expr.index + 1}]`
      return `({ ore_iface ${r} = ${emitExpr(expr.value)}; ${inOrder(expr.args, (args) => `(${fn})(${[`${r}.data`, ...args].join(", ")})`)}; })`
    }
  }
}

/** Prints the member a union value holds; `null` prints as `null`. */
function printUnion(u: UnionType, code: string): string {
  const t = temp()
  const branches = u.members.map((m, i) => {
    const body = m.kind === "null" ? `ore_rt_print_string(ORE_STR("null"));` : `${printCall(raw(payload(u, t, i), m))};`
    return `if (${slotTest(u, t, i)}) { ${body} }`
  })
  return `({ ${cType(u)} ${t} = ${code}; ${branches.join(" else ")} })`
}

/** Formats a printable value as a string, like `print` does. */
function toString(expr: ir.Expr): string {
  const value = emitExpr(expr)
  const t = expr.type
  if (t.kind === "union") {
    const v = temp()
    const r = temp()
    const branches = t.members.map((m, i) => {
      const body = m.kind === "null" ? `ORE_STR("null")` : toString(raw(payload(t, v, i), m))
      return `if (${slotTest(t, v, i)}) ${r} = ${body};`
    })
    return `({ ${cType(t)} ${v} = ${value}; ore_string ${r} = ORE_STR(""); ${branches.join(" else ")} ${r}; })`
  }
  if (t.kind === "literal") return value
  switch (t.kind) {
    case "string":
      return value
    case "int":
      return t.signed ? `ore_rt_str_from_i64((i64)${value})` : `ore_rt_str_from_u64((u64)${value})`
    case "float":
      return `ore_rt_str_from_${t.name}(${value})`
    case "bool":
      return `ore_rt_str_from_bool(${value})`
    default:
      throw new Error(`cannot format ${t.kind}`)
  }
}

/**
 * Declares temporaries for the parts of a place (an array and index, or an
 * object), then `before`, then a pointer `p` to the place. Returns C
 * declarations to put in a statement expression.
 */
function placePointer(target: Exclude<ir.LValue, { k: "local" }>, type: Type, p: string, before = ""): string {
  const t = cType(type)
  if (target.k === "iface-field") {
    const o = temp()
    return `ore_iface ${o} = ${emitExpr(target.value)}; ${before}${t} *${p} = ore_iface_field(${o}, ${target.index});`
  }
  if (target.k === "field") {
    const o = temp()
    return `${cType(target.object.type)} ${o} = ${emitExpr(target.object)}; ${before}${t} *${p} = &${o}->${fieldName(target.name)};`
  }
  const a = temp()
  const i = temp()
  return `ore_array *${a} = ${emitExpr(target.array)}; i64 ${i} = (i64)${emitExpr(target.index)}; ${before}${t} *${p} = ore_rt_array_at(${a}, ${i}, sizeof(${t}));`
}

function emitAssign(expr: ir.Assign): string {
  const target = expr.target
  if (target.k === "local") return `(${access(target.local)} = ${emitExpr(expr.value)})`
  // The parts of the place and the value are evaluated before the pointer is
  // taken, since evaluating the value may grow an array.
  const t = cType(expr.type)
  const v = temp()
  const p = temp()
  const place = placePointer(target, expr.type, p, `${t} ${v} = ${emitExpr(expr.value)}; `)
  if (!expr.op) return `({ ${place} *${p} = ${v}; })`
  const current = raw(`(*${p})`, expr.type)
  const right = raw(v, expr.value.type)
  const combined: ir.Expr =
    expr.type.kind === "string"
      ? { k: "concat", type: types.string, parts: [current, right] }
      : { k: "arith", type: expr.type as ir.IntType | ir.FloatType, op: expr.op, left: current, right }
  return `({ ${place} *${p} = ${emitExpr(combined)}; })`
}

/** A function taking an unused environment that calls a top-level function, for function values. */
function thunk(func: ir.Func): string {
  const name = `${func.name}_thunk`
  if (!helpers.has(name)) {
    const params = func.params.map((p, i) => `${cType(p.type)} a${i}`)
    const args = func.params.map((_, i) => `a${i}`).join(", ")
    const call = `${func.name}(${args})`
    const body = func.type.result.kind === "void" || func.type.result.kind === "never" ? `${call};` : `return ${call};`
    helpers.set(name, `static ${cType(func.type.result)} ${name}(${["void *env_", ...params].join(", ")}) { (void)env_; ${body} }`)
  }
  return name
}

/** A method bound to its receiver: the environment holds the receiver, a thunk calls the method. */
function emitBound(expr: ir.BoundMethod): string {
  const type = expr.type
  const name = expr.func ? `${expr.func.name}_bound` : `ore_iface_bound_${ir.typeKey(type).replace(/[^A-Za-z0-9]/g, "_")}_${expr.index}`
  const receiverType = cType(expr.receiver.type)
  if (!helpers.has(name)) {
    const params = type.params.map((p, i) => `${cType(p)} a${i}`)
    const args = type.params.map((_, i) => `a${i}`)
    let call: string
    if (expr.func) call = `${expr.func.name}(${["*(void **)env_", ...args].join(", ")})`
    else {
      const fn = `(${cType(type.result)} (*)(${["void *", ...type.params.map(cType)].join(", ")}))self.itab[${expr.index! + 1}]`
      call = `(${fn})(${["self.data", ...args].join(", ")})`
    }
    const prelude = expr.func ? "" : "ore_iface self = *(ore_iface *)env_; "
    const body = type.result.kind === "void" || type.result.kind === "never" ? `${call};` : `return ${call};`
    helpers.set(name, `static ${cType(type.result)} ${name}(${["void *env_", ...params].join(", ")}) { ${prelude}${body} }`)
  }
  const e = temp()
  return `({ ${receiverType} *${e} = ore_rt_alloc(sizeof(${receiverType})); *${e} = ${emitExpr(expr.receiver)}; (ore_closure){(void *)${name}, ${e}}; })`
}

/** A call of the closure in C variable `f` with the first arguments it takes. */
function callClosure(f: string, type: ir.FuncType, args: string[]): string {
  const fn = `(${cType(type.result)} (*)(${["void *", ...type.params.map(cType)].join(", ")}))${f}.fn`
  return `(${fn})(${[`${f}.env`, ...args.slice(0, type.params.length)].join(", ")})`
}

function emitArrayMethod(expr: ir.ArrayMethod): string {
  const T = (expr.array.type as ir.ArrayType).elem
  const t = cType(T)
  const a = temp()
  const i = temp()
  const n = temp()
  const f = temp()
  const at = `((${t} *)${a}->data)[${i}]`
  const head = `ore_array *${a} = ${emitExpr(expr.array)};`
  const callback = expr.args[0]
  const cb = callback ? `ore_closure ${f} = ${emitExpr(callback)};` : ""
  const ft = callback?.type as ir.FuncType
  const call = (args: string[]) => callClosure(f, ft, args)
  // Elements present when the call starts, as in JavaScript, while they still exist.
  const loop = (body: string) => `i64 ${n} = ${a}->len; for (i64 ${i} = 0; ${i} < ${n} && ${i} < ${a}->len; ${i}++) { ${body} }`
  const r = temp()
  const x = temp()
  switch (expr.method) {
    case "forEach":
      return `({ ${head} ${cb} ${loop(`${call([at, i])};`)} })`
    case "map": {
      const u = cType((expr.type as ir.ArrayType).elem)
      return `({ ${head} ${cb} ore_array *${r} = ore_rt_array_new(sizeof(${u}), ${a}->len); ${loop(`((${u} *)${r}->data)[${i}] = ${call([at, i])};`)} ${r}; })`
    }
    case "filter":
      return `({ ${head} ${cb} ore_array *${r} = ore_rt_array_new(sizeof(${t}), 0); ${loop(`${t} ${x} = ${at}; if (${call([x, i])}) *(${t} *)ore_rt_array_push(${r}, sizeof(${t})) = ${x};`)} ${r}; })`
    case "find": {
      const u = expr.type as UnionType
      const none = inject(u, u.members.findIndex((m) => m.kind === "null"), "")
      return `({ ${head} ${cb} ${cType(u)} ${r} = ${none}; ${loop(`${t} ${x} = ${at}; if (${call([x, i])}) { ${r} = ${recast(x, T, u)}; break; }`)} ${r}; })`
    }
    case "findIndex":
      return `({ ${head} ${cb} i64 ${r} = -1; ${loop(`if (${call([at, i])}) { ${r} = ${i}; break; }`)} ${r}; })`
    case "some":
      return `({ ${head} ${cb} bool ${r} = false; ${loop(`if (${call([at, i])}) { ${r} = true; break; }`)} ${r}; })`
    case "every":
      return `({ ${head} ${cb} bool ${r} = true; ${loop(`if (!${call([at, i])}) { ${r} = false; break; }`)} ${r}; })`
    case "reduce": {
      const u = cType(expr.type)
      return `({ ${head} ${cb} ${u} ${r} = ${emitExpr(expr.args[1]!)}; ${loop(`${r} = ${call([r, at, i])};`)} ${r}; })`
    }
    case "includes":
    case "indexOf": {
      // includes finds NaN (SameValueZero); indexOf does not (===).
      const same = expr.method === "includes" && T.kind === "float" ? `ore_rt_same_f64(${at}, ${x})` : equals(at, x, T)
      const found = expr.method === "includes" ? [`bool ${r} = false;`, `${r} = true;`] : [`i64 ${r} = -1;`, `${r} = ${i};`]
      return `({ ${head} ${t} ${x} = ${emitExpr(expr.args[0]!)}; ${found[0]} ${loop(`if (${same}) { ${found[1]} break; }`)} ${r}; })`
    }
    case "join": {
      const sep = expr.args[0] ? emitExpr(expr.args[0]) : `ORE_STR(",")`
      return `({ ${head} ore_array *${r} = ore_rt_array_new(sizeof(ore_string), ${a}->len); ${loop(`((ore_string *)${r}->data)[${i}] = ${toString(raw(at, T))};`)} ore_rt_str_join(${r}, ${sep}); })`
    }
    case "reverse":
      return `({ ${head} ore_rt_array_reverse(${a}, sizeof(${t})); ${a}; })`
    default: {
      if (!callback) return `({ ${head} ore_rt_array_sort(${a}, sizeof(${t}), ${naturalOrder(T)}, 0); ${a}; })`
      return `({ ${head} ${cb} ore_rt_array_sort(${a}, sizeof(${t}), ${comparator(ft)}, &${f}); ${a}; })`
    }
  }
}

/** A sort comparison calling a comparator closure, whose number result gives the order. */
function comparator(type: ir.FuncType): string {
  const name = `ore_cmp_${ir.typeKey(type).replace(/[^A-Za-z0-9]/g, (c) => `_${c.charCodeAt(0).toString(16)}`)}`
  if (!helpers.has(name)) {
    const t = cType(type.params[0]!)
    const call = callClosure("(*f)", type, [`*(const ${t} *)a`, `*(const ${t} *)b`])
    helpers.set(name, `static int ${name}(void *ctx, const void *a, const void *b) { ore_closure *f = ctx; ${cType(type.result)} r = ${call}; return r < 0 ? -1 : r > 0 ? 1 : 0; }`)
  }
  return name
}

/** A sort comparison in ascending order of numbers or strings. */
function naturalOrder(type: Type): string {
  const name = `ore_natural_${ir.typeKey(type).replace(/[^A-Za-z0-9]/g, "_")}`
  if (!helpers.has(name)) {
    const t = cType(type)
    const body = isStringLike(type)
      ? `return ore_rt_str_cmp(*(const ore_string *)a, *(const ore_string *)b);`
      : `${t} x = *(const ${t} *)a, y = *(const ${t} *)b; return x < y ? -1 : x > y ? 1 : 0;`
    helpers.set(name, `static int ${name}(void *ctx, const void *a, const void *b) { (void)ctx; ${body} }`)
  }
  return name
}

/** C for a string method, given C for the string and the arguments present. */
function stringMethod(method: string, s: string, a: string[]): string {
  const space = `ORE_STR(" ")`
  switch (method) {
    case "indexOf":
      return `ore_rt_str_index_of(${s}, ${a[0]}, ${a[1] ?? "0"})`
    case "lastIndexOf":
      return `ore_rt_str_last_index_of(${s}, ${a[0]})`
    case "includes":
      return `(ore_rt_str_index_of(${s}, ${a[0]}, 0) != -1)`
    case "startsWith":
      return `ore_rt_str_starts_with(${s}, ${a[0]})`
    case "endsWith":
      return `ore_rt_str_ends_with(${s}, ${a[0]})`
    case "split":
      return `ore_rt_str_split(${s}, ${a[0]})`
    case "trim":
      return `ore_rt_str_trim(${s}, 3)`
    case "trimStart":
      return `ore_rt_str_trim(${s}, 1)`
    case "trimEnd":
      return `ore_rt_str_trim(${s}, 2)`
    case "toUpperCase":
      return `ore_rt_str_case(${s}, true)`
    case "toLowerCase":
      return `ore_rt_str_case(${s}, false)`
    case "replace":
      return `ore_rt_str_replace(${s}, ${a[0]}, ${a[1]}, false)`
    case "replaceAll":
      return `ore_rt_str_replace(${s}, ${a[0]}, ${a[1]}, true)`
    case "repeat":
      return `ore_rt_str_repeat(${s}, ${a[0]})`
    case "padStart":
      return `ore_rt_str_pad(${s}, ${a[0]}, ${a[1] ?? space}, true)`
    case "padEnd":
      return `ore_rt_str_pad(${s}, ${a[0]}, ${a[1] ?? space}, false)`
    default:
      return `ore_rt_str_substring(${s}, ${a[0]}, ${a[1] ?? "INT64_MAX"})`
  }
}

function emitMapOp(expr: ir.MapOp): string {
  const { key: K, value: V } = expr.mapType
  const kt = cType(K)
  const vt = cType(V)
  switch (expr.op) {
    case "new": {
      const { hash, eq } = keyFunctions(K)
      return `ore_rt_map_new(sizeof(${kt}), sizeof(${vt}), ${hash}, ${eq})`
    }
    case "size":
      return `(${emitExpr(expr.map!)})->size`
    case "clear":
      return `ore_rt_map_clear(${emitExpr(expr.map!)})`
    case "keys":
      return `ore_rt_map_keys(${emitExpr(expr.map!)})`
    case "values":
      return `ore_rt_map_values(${emitExpr(expr.map!)})`
  }
  // The map and key (and value) are evaluated in order into temporaries, so the key has an address.
  const m = temp()
  const k = temp()
  const decls = `ore_map *${m} = ${emitExpr(expr.map!)}; ${kt} ${k} = ${emitExpr(expr.key!)};`
  switch (expr.op) {
    case "get": {
      const p = temp()
      const result = expr.type as UnionType
      const none = inject(result, result.members.findIndex((t) => t.kind === "null"), "")
      return `({ ${decls} ${vt} *${p} = ore_rt_map_get(${m}, &${k}); ${p} ? ${recast(`(*${p})`, V, result)} : ${none}; })`
    }
    case "set": {
      const v = temp()
      return `({ ${decls} ${vt} ${v} = ${emitExpr(expr.value!)}; ore_rt_map_set(${m}, &${k}, &${v}); ${m}; })`
    }
    case "has":
      return `({ ${decls} ore_rt_map_get(${m}, &${k}) != 0; })`
    case "delete":
      return `({ ${decls} ore_rt_map_delete(${m}, &${k}); })`
  }
}

/**
 * Emits operands left to right, as Ore requires and C does not guarantee for
 * arguments and binary operators. When an operand has effects and another
 * operand is not a literal, every operand but the last is evaluated into a
 * temporary first.
 */
function inOrder(exprs: ir.Expr[], build: (codes: string[]) => string): string {
  const needsOrder = exprs.some(effects) && exprs.filter((e) => !isLiteral(e)).length >= 2
  if (!needsOrder) return build(exprs.map(emitExpr))
  const decls: string[] = []
  const codes = exprs.map((e, i) => {
    const code = emitExpr(e)
    if (i === exprs.length - 1 || isLiteral(e) || e.type.kind === "never") return code
    const t = temp()
    decls.push(`${cType(e.type)} ${t} = ${code};`)
    return t
  })
  return `({ ${decls.join(" ")} ${build(codes)}; })`
}

function isLiteral(e: ir.Expr): boolean {
  return e.k === "int" || e.k === "float" || e.k === "bool" || e.k === "string"
}

/** Whether evaluating an expression may have an observable effect, including a panic. */
function effects(e: ir.Expr): boolean {
  switch (e.k) {
    case "int":
    case "float":
    case "bool":
    case "string":
    case "local":
    case "alloc":
      return false
    case "call":
    case "method-call":
    case "builtin":
    case "assign":
    case "incdec":
    case "push":
    case "pop":
    case "index":
      return true
    case "arith":
      return e.op === "/" || e.op === "%" || e.op === "<<" || e.op === ">>" || effects(e.left) || effects(e.right)
    case "compare":
    case "logical":
      return effects(e.left) || effects(e.right)
    case "unary":
    case "not":
      return effects(e.operand)
    case "convert":
      return effects(e.value)
    case "cond":
      return effects(e.cond) || effects(e.then) || effects(e.else)
    case "concat":
      return e.parts.some(effects)
    case "len":
      return effects(e.value)
    case "slice":
      return effects(e.value) || (e.start !== undefined && effects(e.start)) || (e.end !== undefined && effects(e.end))
    case "array":
      return e.elems.some(effects)
    case "object":
      return e.fields.some((f) => effects(f.value))
    case "field":
      return effects(e.object)
    case "to-iface":
    case "iface-field":
    case "is-null":
    case "union-field":
    case "typeof":
    case "is":
      return effects(e.value)
    case "null":
    case "func-ref":
    case "closure":
      return false
    case "bound-method":
      return effects(e.receiver)
    case "iface-call":
    case "downcast":
    case "map":
    case "call-value":
    case "array-method":
    case "string-method":
    case "recast":
    case "optional":
    case "coalesce":
      return true
  }
}

function emitArith(expr: ir.Arith): string {
  if (effects(expr.left) || effects(expr.right)) {
    return inOrder([expr.left, expr.right], ([l, r]) => emitArith({ ...expr, left: raw(l!, expr.left.type), right: raw(r!, expr.right.type) }))
  }
  const t = expr.type
  const l = emitExpr(expr.left)
  const r = emitExpr(expr.right)
  if (t.kind === "float") {
    if (expr.op === "%") return `${t.bits === 32 ? "ore_fmodf" : "ore_fmod"}(${l}, ${r})`
    return `((${t.name})(${l} ${expr.op} ${r}))`
  }
  switch (expr.op) {
    case "/":
      return `ore_div_${t.name}(${l}, ${r})`
    case "%":
      return `ore_rem_${t.name}(${l}, ${r})`
    case "<<":
    case ">>": {
      const count = expr.right.type as IntType
      const n = count.signed ? `ore_shift_count((i64)${r})` : `((u64)${r})`
      return `ore_${expr.op === "<<" ? "shl" : "shr"}_${t.name}(${l}, ${n})`
    }
    default:
      // Operands narrower than int are promoted by C; the cast wraps the result back.
      return `((${t.name})(${l} ${expr.op} ${r}))`
  }
}

function emitConvert(expr: ir.Convert): string {
  const from = expr.value.type
  const value = emitExpr(expr.value)
  if (expr.type.kind === "int" && from.kind === "float") return `ore_f2i_${expr.type.name}((f64)${value})`
  return `((${expr.type.name})${value})`
}

/** C for built-in functions other than printing, by name, given C for their arguments. */
const builtins: Record<string, (a: string[], expr: ir.BuiltinCall) => string> = {
  "process.panic": (a) => `ore_rt_panic(${a[0]})`,
  "process.exit": (a) => `ore_rt_exit(${a[0]})`,
  "Math.abs": (a, e) => (e.type.kind === "float" ? `fabs(${a[0]})` : `({ ${cType(e.type)} x_ = ${a[0]}; (${cType(e.type)})(x_ < 0 ? -x_ : x_); })`),
  "Math.min": (a, e) => `({ ${cType(e.type)} a_ = ${a[0]}, b_ = ${a[1]}; ${e.type.kind === "float" ? "a_ != a_ || b_ != b_ ? NAN : " : ""}(b_ < a_ ? b_ : a_); })`,
  "Math.max": (a, e) => `({ ${cType(e.type)} a_ = ${a[0]}, b_ = ${a[1]}; ${e.type.kind === "float" ? "a_ != a_ || b_ != b_ ? NAN : " : ""}(b_ > a_ ? b_ : a_); })`,
  "Math.round": (a) => `ore_rt_round(${a[0]})`,
  "Math.sign": (a) => `({ f64 x_ = ${a[0]}; x_ > 0 ? 1.0 : x_ < 0 ? -1.0 : x_; })`,
  "Math.random": () => "ore_rt_random()",
  "Number.toFixed": (a) => `ore_rt_str_fixed(${a[0]}, ${a[1]})`,
  "Number.parseInt": (a, e) => maybe(e, "i64", `ore_rt_parse_int(${a[0]}, ${a[1] ?? "0"}, &v_)`),
  "Number.parseFloat": (a, e) => maybe(e, "f64", `ore_rt_parse_float(${a[0]}, &v_)`),
  "fs.readFile": (a, e) => fallible(e, "ore_string", `ore_rt_read_file(${a[0]}, &v_)`, "v_"),
  "fs.writeFile": (a, e) => fallible(e, undefined, `ore_rt_write_file(${a[0]}, ${a[1]}, &v_)`, "v_"),
  "fs.exists": (a) => `ore_rt_file_exists(${a[0]})`,
  "Date.now": () => "ore_rt_now()",
  "process.args": () => "ore_rt_args()",
  "process.getenv": (a) => `ore_rt_getenv(${a[0]})`,
}

/** A `T | null` from a runtime call that stores the value in `v_` and returns whether there is one. */
function maybe(expr: ir.BuiltinCall, t: string, call: string): string {
  const u = expr.type as UnionType
  const value = u.members.findIndex((m) => m.kind !== "null")
  const none = inject(u, u.members.findIndex((m) => m.kind === "null"), "")
  return `({ ${t} v_; ${call} ? ${inject(u, value, "v_")} : ${none}; })`
}

/**
 * A `T | Error` (or `Error | null` without a value type) from a runtime call
 * that stores the value or the error message in `v_` and returns success.
 */
function fallible(expr: ir.BuiltinCall, t: string | undefined, call: string, v: string): string {
  const u = expr.type as UnionType
  const { ctor, itab } = expr.error!
  const error = u.members.findIndex((m) => m.kind === "interface")
  const fail = inject(u, error, `((ore_iface){(void *)${ctor.name}(${v}), ore_itab_${itab.id}})`)
  const ok = t ? inject(u, u.members.findIndex((m) => m.kind !== "interface"), v) : inject(u, u.members.findIndex((m) => m.kind === "null"), "")
  return `({ ore_string ${t ? "" : ""}v_; ${call} ? ${ok} : ${fail}; })`
}
for (const f of ["sqrt", "cbrt", "pow", "exp", "log", "log2", "log10", "sin", "cos", "tan", "asin", "acos", "atan", "atan2", "hypot", "floor", "ceil", "trunc"]) {
  builtins[`Math.${f}`] = (a) => `${f}(${a.join(", ")})`
}

function emitBuiltin(expr: ir.BuiltinCall): string {
  const special = builtins[expr.name]
  if (special) return inOrder(expr.args, (a) => special(a, expr))
  const parts: string[] = []
  if (expr.name === "console.error") parts.push("ore_rt_print_to(2)")
  expr.args.forEach((arg, i) => {
    if (i > 0) parts.push("ore_rt_print_space()")
    parts.push(printCall(arg))
  })
  if (expr.name !== "console.write") parts.push("ore_rt_print_newline()")
  if (expr.name === "console.error") parts.push("ore_rt_print_to(1)")
  return parts.length === 0 ? "((void)0)" : `(${parts.join(", ")})`
}

function printCall(arg: ir.Expr): string {
  const value = emitExpr(arg)
  const t = arg.type
  if (t.kind === "union") return printUnion(t, value)
  if (t.kind === "literal") return `ore_rt_print_string(${value})`
  switch (t.kind) {
    case "int":
      return t.signed ? `ore_rt_print_i64((i64)${value})` : `ore_rt_print_u64((u64)${value})`
    case "float":
      return `ore_rt_print_${t.name}(${value})`
    case "bool":
      return `ore_rt_print_bool(${value})`
    case "string":
      return `ore_rt_print_string(${value})`
    default:
      throw new Error(`cannot print ${t.kind}`)
  }
}

