// Literals

export function intLiteral(type: IntType, value: bigint): string {
  if (value >= 0n) return `((${type.name})${value}ULL)`
  // The most negative i64 has no literal form; build every negative value from value + 1.
  return `((${type.name})(${value + 1n}LL - 1))`
}

export function floatLiteral(type: FloatType, value: number): string {
  const suffix = type.bits === 32 ? "f" : ""
  if (Number.isNaN(value)) return `((${type.name})__builtin_nan(""))`
  if (!Number.isFinite(value)) return `((${type.name})${value < 0 ? "-" : ""}__builtin_inf())`
  // String(-0) is "0".
  let text = Object.is(value, -0) ? "-0" : String(value)
  if (!/[.e]/.test(text)) text += ".0"
  return `(${text}${suffix})`
}

/** A C string literal; every byte outside printable ASCII is an octal escape. */
/** What `typeof` gives for values of a type. */
function typeofName(type: Type): string {
  if (ir.isNumeric(type)) return "number"
  if (type.kind === "bool") return "boolean"
  if (isStringLike(type)) return "string"
  return "object"
}

export function stringLiteral(value: string): string {
  let out = '"'
  for (const byte of new TextEncoder().encode(value)) {
    const c = String.fromCharCode(byte)
    if (c === '"' || c === "\\") out += `\\${c}`
    else if (byte >= 0x20 && byte < 0x7f && c !== "?") out += c
    else out += `\\${byte.toString(8).padStart(3, "0")}`
  }
  return `${out}"`
}
