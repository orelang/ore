import type * as ir from "@ore/ir"
import type { FloatType, IntType, Type } from "@ore/ir"

/** Emits a C translation unit for a module. Requires `ore.h` from the runtime. */
export function emitModule(module: ir.Module): string {
  const out: string[] = ["// Generated by the Ore compiler. Do not edit.", '#include "ore.h"', ""]
  for (const func of module.functions) out.push(`static ${signature(func)};`)
  out.push("")
  for (const func of module.functions) {
    out.push(`static ${signature(func)} ${emitBlock(func.body, 0)}`, "")
  }
  const main = module.functions.find((f) => f.sourceName === "main")
  if (main) out.push(`void ore_entry(void) { ${main.name}(); }`, "")
  return out.join("\n")
}

function signature(func: ir.Func): string {
  const params = func.params.length === 0 ? "void" : func.params.map((p) => `${cType(p.type)} ${localName(p)}`).join(", ")
  return `${cType(func.type.result)} ${func.name}(${params})`
}

export function cType(type: Type): string {
  switch (type.kind) {
    case "int":
    case "float":
      return type.name
    case "bool":
      return "bool"
    case "string":
      return "ore_string"
    case "void":
    case "never":
      return "void"
    case "func":
      throw new Error("function types are not supported by the C backend yet")
  }
}

/** Locals are suffixed with their id: unique per function and never a C keyword. */
function localName(local: ir.Local): string {
  return `${sanitize(local.name)}_${local.id}`
}

function sanitize(name: string): string {
  return name.replace(/[^A-Za-z0-9_]/g, (c) => `_x${c.codePointAt(0)!.toString(16)}_`)
}

// -----------------------------------------------------------------------------
// Statements

function indent(depth: number): string {
  return "  ".repeat(depth)
}

function emitBlock(block: ir.Block, depth: number): string {
  if (block.body.length === 0) return "{}"
  const lines = block.body.map((s) => indent(depth + 1) + emitStmt(s, depth + 1))
  return `{\n${lines.join("\n")}\n${indent(depth)}}`
}

/** Emits a statement as a braced block, for branches and loop bodies. */
function emitBody(stmt: ir.Stmt, depth: number): string {
  return emitBlock(stmt.k === "block" ? stmt : { k: "block", body: [stmt] }, depth)
}

function emitStmt(stmt: ir.Stmt, depth: number): string {
  switch (stmt.k) {
    case "block":
      return emitBlock(stmt, depth)
    case "let":
      return `${cType(stmt.local.type)} ${localName(stmt.local)} = ${emitExpr(stmt.init)};`
    case "expr":
      return `${emitExpr(stmt.expr)};`
    case "if": {
      let s = `if (${emitExpr(stmt.cond)}) ${emitBody(stmt.then, depth)}`
      if (stmt.else) s += ` else ${stmt.else.k === "if" ? emitStmt(stmt.else, depth) : emitBody(stmt.else, depth)}`
      return s
    }
    case "loop": {
      const body = emitBody(stmt.body, depth)
      if (stmt.condAfter) return `do ${body} while (${emitExpr(stmt.cond!)});`
      const cond = stmt.cond ? emitExpr(stmt.cond) : ""
      const update = stmt.update ? emitExpr(stmt.update) : ""
      return `for (; ${cond}; ${update}) ${body}`
    }
    case "break":
      return "break;"
    case "continue":
      return "continue;"
    case "return":
      return stmt.value ? `return ${emitExpr(stmt.value)};` : "return;"
  }
}

// -----------------------------------------------------------------------------
// Expressions (always fully parenthesized)

const cCompare: Record<ir.CompareOp, string> = { "===": "==", "!==": "!=", "<": "<", "<=": "<=", ">": ">", ">=": ">=" }

function emitExpr(expr: ir.Expr): string {
  switch (expr.k) {
    case "int":
      return intLiteral(expr.type, expr.value)
    case "float":
      return floatLiteral(expr.type, expr.value)
    case "bool":
      return expr.value ? "true" : "false"
    case "string":
      return `ORE_STR(${stringLiteral(expr.value)})`
    case "local":
      return localName(expr.local)
    case "assign":
      return `(${localName(expr.target)} = ${emitExpr(expr.value)})`
    case "incdec": {
      const name = localName(expr.target)
      return expr.prefix ? `(${expr.op}${name})` : `(${name}${expr.op})`
    }
    case "arith":
      return emitArith(expr)
    case "compare": {
      const l = emitExpr(expr.left)
      const r = emitExpr(expr.right)
      if (expr.left.type.kind === "string") {
        return `(${expr.op === "===" ? "" : "!"}ore_rt_str_eq(${l}, ${r}))`
      }
      return `(${l} ${cCompare[expr.op]} ${r})`
    }
    case "logical":
      return `(${emitExpr(expr.left)} ${expr.op} ${emitExpr(expr.right)})`
    case "unary":
      return expr.type.kind === "float" ? `(${expr.op}${emitExpr(expr.operand)})` : `((${expr.type.name})${expr.op}${emitExpr(expr.operand)})`
    case "not":
      return `(!${emitExpr(expr.operand)})`
    case "convert":
      return emitConvert(expr)
    case "call":
      return `${expr.func.name}(${expr.args.map(emitExpr).join(", ")})`
    case "builtin":
      return emitBuiltin(expr)
    case "cond":
      return `(${emitExpr(expr.cond)} ? ${emitExpr(expr.then)} : ${emitExpr(expr.else)})`
  }
}

function emitArith(expr: ir.Arith): string {
  const t = expr.type
  const l = emitExpr(expr.left)
  const r = emitExpr(expr.right)
  if (t.kind === "float") {
    if (expr.op === "%") return `${t.bits === 32 ? "ore_fmodf" : "ore_fmod"}(${l}, ${r})`
    return `((${t.name})(${l} ${expr.op} ${r}))`
  }
  switch (expr.op) {
    case "/":
      return `ore_div_${t.name}(${l}, ${r})`
    case "%":
      return `ore_rem_${t.name}(${l}, ${r})`
    case "<<":
    case ">>": {
      const count = expr.right.type as IntType
      const n = count.signed ? `ore_shift_count((i64)${r})` : `((u64)${r})`
      return `ore_${expr.op === "<<" ? "shl" : "shr"}_${t.name}(${l}, ${n})`
    }
    default:
      // Operands narrower than int are promoted by C; the cast wraps the result back.
      return `((${t.name})(${l} ${expr.op} ${r}))`
  }
}

function emitConvert(expr: ir.Convert): string {
  const from = expr.value.type
  const value = emitExpr(expr.value)
  if (expr.type.kind === "int" && from.kind === "float") return `ore_f2i_${expr.type.name}((f64)${value})`
  return `((${expr.type.name})${value})`
}

function emitBuiltin(expr: ir.BuiltinCall): string {
  if (expr.name === "panic") return `ore_rt_panic(${emitExpr(expr.args[0]!)})`
  const parts: string[] = []
  expr.args.forEach((arg, i) => {
    if (i > 0) parts.push("ore_rt_print_space()")
    parts.push(printCall(arg))
  })
  if (expr.name === "println") parts.push("ore_rt_print_newline()")
  return parts.length === 0 ? "((void)0)" : `(${parts.join(", ")})`
}

function printCall(arg: ir.Expr): string {
  const value = emitExpr(arg)
  const t = arg.type
  switch (t.kind) {
    case "int":
      return t.signed ? `ore_rt_print_i64((i64)${value})` : `ore_rt_print_u64((u64)${value})`
    case "float":
      return `ore_rt_print_${t.name}(${value})`
    case "bool":
      return `ore_rt_print_bool(${value})`
    case "string":
      return `ore_rt_print_string(${value})`
    default:
      throw new Error(`cannot print ${t.kind}`)
  }
}

// -----------------------------------------------------------------------------
// Literals

export function intLiteral(type: IntType, value: bigint): string {
  if (value >= 0n) return `((${type.name})${value}ULL)`
  // The most negative i64 has no literal form; build every negative value from value + 1.
  return `((${type.name})(${value + 1n}LL - 1))`
}

export function floatLiteral(type: FloatType, value: number): string {
  const suffix = type.bits === 32 ? "f" : ""
  if (Number.isNaN(value)) return `((${type.name})__builtin_nan(""))`
  if (!Number.isFinite(value)) return `((${type.name})${value < 0 ? "-" : ""}__builtin_inf())`
  let text = String(value)
  if (!/[.e]/.test(text)) text += ".0"
  return `(${text}${suffix})`
}

/** A C string literal; every byte outside printable ASCII is an octal escape. */
export function stringLiteral(value: string): string {
  let out = '"'
  for (const byte of new TextEncoder().encode(value)) {
    const c = String.fromCharCode(byte)
    if (c === '"' || c === "\\") out += `\\${c}`
    else if (byte >= 0x20 && byte < 0x7f && c !== "?") out += c
    else out += `\\${byte.toString(8).padStart(3, "0")}`
  }
  return `${out}"`
}
