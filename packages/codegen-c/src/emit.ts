import * as ir from "@ore/ir"
import { isStringLike, types, unionRepr, type FloatType, type IntType, type Type, type UnionType } from "@ore/ir"

export interface EmitOptions {
  /**
   * Keep a shadow stack of frames for panic stack traces and map the C code
   * to Ore source lines with `#line`.
   */
  debug: boolean
}

interface Context {
  debug: boolean
  /** The source path as a C string literal. */
  file: string
  func: ir.Func
}

/** Emits a C translation unit for a module. Requires `ore.h` from the runtime. */
export function emitModule(module: ir.Module, options: EmitOptions = { debug: false }): string {
  const out: string[] = ["// Generated by the Ore compiler. Do not edit.", '#include "ore.h"', ""]
  for (const s of module.structs) out.push(`typedef struct ${structName(s)} ${structName(s)};`)
  // Unions hold structs only by pointer, so they come before struct definitions.
  for (const u of module.unions) if (unionRepr(u).k === "tagged") out.push(...emitUnion(u))
  for (const s of module.structs) out.push(emitStruct(s))
  for (const func of module.functions) out.push(`static ${signature(func)};`)
  for (const itab of module.itabs) out.push(emitItab(itab))
  out.push("")
  const file = JSON.stringify(module.file)
  for (const func of module.functions) out.push(emitFunction({ debug: options.debug, file, func }), "")
  const main = module.functions.find((f) => f.sourceName === "main")
  if (main) out.push(`void ore_entry(void) { ${main.name}(); }`, "")
  return out.join("\n")
}

const frame = "ore_frame_"

function emitFunction(ctx: Context): string {
  const { func } = ctx
  const lines = func.body.body.map((s) => emitLine(s, 0, ctx))
  // Methods take `this` untyped so that interface tables can call them uniformly.
  if (func.receiver) lines.unshift(`  ${cType(func.receiver.type)} ${localName(func.receiver)} = self_;`)
  if (ctx.debug) {
    lines.unshift(
      `  ore_frame ${frame} = {ore_rt_top, ${JSON.stringify(func.sourceName)}, ${ctx.file}, ${func.line}};`,
      `  ore_rt_top = &${frame};`,
    )
    if (func.type.result.kind === "void") lines.push(`  ore_rt_top = ${frame}.prev;`)
  }
  const header = `static ${signature(func)}`
  return lines.length === 0 ? `${header} {}` : `${header} {\n${lines.join("\n")}\n}`
}

function structName(s: ir.StructType): string {
  return s.nominal ? `ore_C_${sanitize(s.name!)}` : `ore_obj_${s.id}`
}

function fieldName(name: string): string {
  return `f_${sanitize(name)}`
}

function emitStruct(s: ir.StructType): string {
  // C has no empty structs.
  const fields = s.fields.length === 0 ? ["char unused_;"] : s.fields.map((f) => `${cType(f.type)} ${fieldName(f.name)};`)
  return `struct ${structName(s)} { ${fields.join(" ")} };`
}

function unionName(u: UnionType): string {
  return `ore_union_${u.id}`
}

function emitUnion(u: UnionType): string[] {
  const name = unionName(u)
  const payloads = u.members.flatMap((m, i) => (m.kind === "null" ? [] : [`${cType(m)} s${i};`]))
  const equal = u.members.map((m, i) => `case ${i}: return ${m.kind === "null" ? "true" : equals(`a.as.s${i}`, `b.as.s${i}`, m)};`)
  return [
    `typedef struct { i32 tag; union { ${payloads.join(" ")} } as; } ${name};`,
    `static bool ${name}_eq(${name} a, ${name} b) { if (a.tag != b.tag) return false; switch (a.tag) { ${equal.join(" ")} } return false; }`,
  ]
}

/** C equality of two values of a non-union type, as `===`. */
function equals(a: string, b: string, type: Type): string {
  if (isStringLike(type)) return `ore_rt_str_eq(${a}, ${b})`
  if (type.kind === "interface") return `(${a}.data == ${b}.data)`
  return `(${a} == ${b})`
}

// The run-time representation of unions; see `unionRepr`.

/** C test that a union value `v` (a pure expression) holds member `i`. */
function slotTest(u: UnionType, v: string, i: number): string {
  const repr = unionRepr(u)
  if (repr.k === "tagged") return `(${v}.tag == ${i})`
  const member = u.members[i]!
  // Members that are string literals are told apart by the value.
  const literal = member.kind === "literal" ? `ore_rt_str_eq(${v}, ORE_STR(${stringLiteral(member.value)}))` : undefined
  if (repr.k === "strings") return `(${literal})`
  if (member.kind === "null") return isNullRef(v, repr.base)
  return literal ? `(!${isNullRef(v, repr.base)} && ${literal})` : `!${isNullRef(v, repr.base)}`
}

/** The value of member `i` of a union value `v` (a pure expression). */
function payload(u: UnionType, v: string, i: number): string {
  return unionRepr(u).k === "tagged" ? `${v}.as.s${i}` : v
}



/** A union value holding member `i` with value `p` (unused for `null`). */
function inject(u: UnionType, i: number, p: string): string {
  const repr = unionRepr(u)
  const isNullMember = u.members[i]!.kind === "null"
  if (repr.k === "strings") return p
  if (repr.k === "nullable") return isNullMember ? nullRef(repr.base) : p
  return isNullMember ? `((${unionName(u)}){.tag = ${i}})` : `((${unionName(u)}){.tag = ${i}, .as.s${i} = ${p}})`
}

function nullRef(base: Type): string {
  if (base.kind === "interface") return "((ore_iface){0})"
  if (base.kind === "string") return "((ore_string){0})"
  return `((${cType(base)})0)`
}

function isNullRef(v: string, base: Type): string {
  if (base.kind === "interface") return `(${v}.data == 0)`
  if (base.kind === "string") return `(${v}.ptr == 0)`
  return `(${v} == 0)`
}

/** The member of a union that holds values of a type; a string literal also fits `string`. */
function memberIndex(u: UnionType, type: Type): number {
  const exact = u.members.findIndex((m) => ir.sameType(m, type))
  if (exact !== -1 || type.kind !== "literal") return exact
  return u.members.findIndex((m) => m.kind === "string")
}

/**
 * Converts `code` from type `from` to type `to`, where one is a union holding
 * the members of the other. Narrowing panics on a member the target lacks.
 */
function recast(code: string, from: Type, to: Type): string {
  // Unions of string literals widen to `string` without a change.
  if (from.kind === "union" && unionRepr(from).k === "strings" && to.kind === "string") return code
  if (from.kind !== "union") {
    if (to.kind !== "union") return code
    return inject(to, memberIndex(to, from), code)
  }
  const t = temp()
  const check = (i: number) => slotTest(from, t, i)
  if (to.kind !== "union") {
    const i = memberIndex(from, to)
    const message = from.members.some((m) => m.kind === "null") && from.members.length === 2 ? "unexpected null" : `value is not of type ${ir.typeToString(to)}`
    return `({ ${cType(from)} ${t} = ${code}; if (!${check(i)}) ore_rt_panic_cstr(${stringLiteral(message)}); ${payload(from, t, i)}; })`
  }
  // Union to union: map each member of the source to the target.
  const r = temp()
  const branches = from.members.map((m, i) => {
    const j = memberIndex(to, m)
    const body = j === -1 ? `ore_rt_panic_cstr(${stringLiteral(`value is not of type ${ir.typeToString(to)}`)});` : `${r} = ${inject(to, j, payload(from, t, i))};`
    return `if (${check(i)}) ${body}`
  })
  return `({ ${cType(from)} ${t} = ${code}; ${cType(to)} ${r}; ${branches.join(" else ")} ${r}; })`
}

function isNullValue(u: UnionType, v: string): string {
  return slotTest(u, v, u.members.findIndex((m) => m.kind === "null"))
}

function emitItab(itab: ir.Itab): string {
  const s = structName(itab.struct)
  const entries = itab.iface.members.map((m) => {
    if (m.k === "field") return `(void *)(uintptr_t)offsetof(${s}, ${fieldName(m.name)})`
    return `(void *)${ir.findMethod(itab.struct, m.name)!.func.name}`
  })
  return `static void *const ore_itab_${itab.id}[] = { ${[`(void *)(uintptr_t)${typeId(itab.struct)}`, ...entries].join(", ")} };`
}

/** The id of a struct in interface tables; never 0. */
function typeId(s: ir.StructType): number {
  return s.id + 1
}

function signature(func: ir.Func): string {
  const list = func.params.map((p) => `${cType(p.type)} ${localName(p)}`)
  if (func.receiver) list.unshift("void *self_")
  const params = list.length === 0 ? "void" : list.join(", ")
  return `${cType(func.type.result)} ${func.name}(${params})`
}

export function cType(type: Type): string {
  switch (type.kind) {
    case "int":
    case "float":
      return type.name
    case "bool":
      return "bool"
    case "string":
      return "ore_string"
    case "void":
    case "never":
      return "void"
    case "array":
      return "ore_array *"
    case "struct":
      return `${structName(type)} *`
    case "interface":
      return "ore_iface"
    case "union": {
      const repr = unionRepr(type)
      if (repr.k === "strings") return "ore_string"
      return repr.k === "nullable" ? cType(repr.base) : unionName(type)
    }
    case "literal":
      return "ore_string"
    case "null":
      return "void *"
    case "func":
      throw new Error("function types are not supported by the C backend yet")
  }
}

let tempCounter = 0

/** A fresh C identifier for a temporary; never clashes with locals, which end in `_<id>`. */
function temp(): string {
  return `t${tempCounter++}_`
}

/**
 * An expression already emitted as C, used to reuse `emitExpr` logic on
 * temporaries. Exists only inside the C backend.
 */
interface Raw {
  k: "raw"
  type: Type
  code: string
}

function raw(code: string, type: Type): ir.Expr {
  return { k: "raw", type, code } satisfies Raw as unknown as ir.Expr
}

/** Locals are suffixed with their id: unique per function and never a C keyword. */
function localName(local: ir.Local): string {
  return `${sanitize(local.name)}_${local.id}`
}

function sanitize(name: string): string {
  return name.replace(/[^A-Za-z0-9_]/g, (c) => `_x${c.codePointAt(0)!.toString(16)}_`)
}

// -----------------------------------------------------------------------------
// Statements

function indent(depth: number): string {
  return "  ".repeat(depth)
}

/** A statement inside a block at `depth`, prefixed with its source line in debug builds. */
function emitLine(stmt: ir.Stmt, depth: number, ctx: Context): string {
  const code = indent(depth + 1) + emitStmt(stmt, depth + 1, ctx)
  if (!ctx.debug || stmt.line === undefined) return code
  return `#line ${stmt.line} ${ctx.file}\n${indent(depth + 1)}${frame}.line = ${stmt.line};\n${code}`
}

function emitBlock(block: ir.Block, depth: number, ctx: Context): string {
  if (block.body.length === 0) return "{}"
  return `{\n${block.body.map((s) => emitLine(s, depth, ctx)).join("\n")}\n${indent(depth)}}`
}

/** Emits a statement as a braced block, for branches and loop bodies. */
function emitBody(stmt: ir.Stmt, depth: number, ctx: Context): string {
  return emitBlock(stmt.k === "block" ? stmt : { k: "block", body: [stmt] }, depth, ctx)
}

function emitStmt(stmt: ir.Stmt, depth: number, ctx: Context): string {
  switch (stmt.k) {
    case "block":
      return emitBlock(stmt, depth, ctx)
    case "let":
      return `${cType(stmt.local.type)} ${localName(stmt.local)} = ${emitExpr(stmt.init)};`
    case "expr":
      return `${emitExpr(stmt.expr)};`
    case "if": {
      let s = `if (${emitExpr(stmt.cond)}) ${emitBody(stmt.then, depth, ctx)}`
      if (stmt.else) s += ` else ${stmt.else.k === "if" ? emitStmt(stmt.else, depth, ctx) : emitBody(stmt.else, depth, ctx)}`
      return s
    }
    case "loop": {
      // A labeled continue jumps to the end of the body, so the update and
      // condition still run; a labeled break jumps past the loop.
      const lines = (stmt.body.k === "block" ? stmt.body.body : [stmt.body]).map((s) => emitLine(s, depth, ctx))
      if (stmt.labeled) lines.push(`${indent(depth + 1)}continue_${stmt.id}:;`)
      const body = lines.length === 0 ? "{}" : `{\n${lines.join("\n")}\n${indent(depth)}}`
      const after = stmt.labeled ? `\n${indent(depth)}break_${stmt.id}:;` : ""
      if (stmt.condAfter) return `do ${body} while (${emitExpr(stmt.cond!)});${after}`
      const cond = stmt.cond ? emitExpr(stmt.cond) : ""
      const update = stmt.update ? emitExpr(stmt.update) : ""
      return `for (; ${cond}; ${update}) ${body}${after}`
    }
    case "for-of": {
      const lines = (stmt.body.k === "block" ? stmt.body.body : [stmt.body]).map((s) => emitLine(s, depth + 1, ctx))
      if (stmt.labeled) lines.push(`${indent(depth + 2)}continue_${stmt.id}:;`)
      const name = localName(stmt.local)
      const elem = cType(stmt.local.type)
      const it = temp()
      const i = temp()
      let head: string
      let first: string
      if (stmt.iterable.type.kind === "string") {
        head = `ore_string ${it} = ${emitExpr(stmt.iterable)};\n${indent(depth + 1)}for (i64 ${i} = 0; ${i} < ${it}.len;)`
        first = `${elem} ${name} = ore_rt_str_decode(${it}, &${i});`
      } else {
        head = `ore_array *${it} = ${emitExpr(stmt.iterable)};\n${indent(depth + 1)}for (i64 ${i} = 0; ${i} < ${it}->len; ${i}++)`
        first = `${elem} ${name} = ((${elem} *)${it}->data)[${i}];`
      }
      const body = [`${indent(depth + 2)}${first}`, ...lines].join("\n")
      const after = stmt.labeled ? `\n${indent(depth)}break_${stmt.id}:;` : ""
      return `{\n${indent(depth + 1)}${head} {\n${body}\n${indent(depth + 1)}}\n${indent(depth)}}${after}`
    }
    case "switch": {
      // Find the clause index with the tests in order, then enter a C switch
      // over the index, whose `case` labels fall through like Ore's.
      const index = temp()
      const tests = stmt.clauses.flatMap((c, i) => (c.test ? [`if (${emitExpr(c.test)}) ${index} = ${i};`] : []))
      const fallback = stmt.clauses.findIndex((c) => !c.test)
      const select = [...tests, `${index} = ${fallback};`].join(" else ")
      const pad = indent(depth + 1)
      const cases = stmt.clauses.flatMap((c, i) => [`${pad}case ${i}: {}`, ...c.body.map((s) => emitLine(s, depth, ctx))])
      const after = stmt.labeled ? `\n${indent(depth)}break_${stmt.id}:;` : ""
      return [
        "{",
        `${pad}${cType(stmt.local.type)} ${localName(stmt.local)} = ${emitExpr(stmt.value)};`,
        `${pad}i32 ${index};`,
        `${pad}${select}`,
        `${pad}switch (${index}) {`,
        ...cases,
        `${pad}}`,
        `${indent(depth)}}${after}`,
      ].join("\n")
    }
    case "break":
      return stmt.target === undefined ? "break;" : `goto break_${stmt.target};`
    case "continue":
      return stmt.target === undefined ? "continue;" : `goto continue_${stmt.target};`
    case "return": {
      if (!ctx.debug) return stmt.value ? `return ${emitExpr(stmt.value)};` : "return;"
      // Pop the frame after evaluating the value, which may call other functions.
      if (!stmt.value) return `{ ore_rt_top = ${frame}.prev; return; }`
      return `{ ${cType(stmt.value.type)} ore_ret_ = ${emitExpr(stmt.value)}; ore_rt_top = ${frame}.prev; return ore_ret_; }`
    }
  }
}

// -----------------------------------------------------------------------------
// Expressions (always fully parenthesized)

const cCompare: Record<ir.CompareOp, string> = { "===": "==", "!==": "!=", "<": "<", "<=": "<=", ">": ">", ">=": ">=" }

function emitExpr(expr: ir.Expr): string {
  if ((expr as unknown as Raw).k === "raw") return (expr as unknown as Raw).code
  switch (expr.k) {
    case "int":
      return intLiteral(expr.type, expr.value)
    case "float":
      return floatLiteral(expr.type, expr.value)
    case "bool":
      return expr.value ? "true" : "false"
    case "string":
      return `ORE_STR(${stringLiteral(expr.value)})`
    case "local":
      return localName(expr.local)
    case "assign":
      return emitAssign(expr)
    case "incdec": {
      if (expr.target.k === "local") {
        const name = localName(expr.target.local)
        return expr.prefix ? `(${expr.op}${name})` : `(${name}${expr.op})`
      }
      const p = temp()
      const place = placePointer(expr.target, expr.type, p)
      return `({ ${place} ${expr.prefix ? `${expr.op}(*${p})` : `(*${p})${expr.op}`}; })`
    }
    case "arith":
      return emitArith(expr)
    case "compare":
      return inOrder([expr.left, expr.right], ([l, r]) => {
        if (expr.left.type.kind === "string" && expr.op !== "===" && expr.op !== "!==") return `(ore_rt_str_cmp(${l}, ${r}) ${expr.op} 0)`
        // Interface values are equal when they refer to the same object.
        if (expr.left.type.kind === "interface") return `((${l}).data ${cCompare[expr.op]} (${r}).data)`
        if (isStringLike(expr.left.type)) {
          const eq = `ore_rt_str_eq(${l}, ${r})`
          return expr.op === "===" ? eq : `(!${eq})`
        }
        if (expr.left.type.kind === "union") {
          const u = expr.left.type
          const repr = unionRepr(u)
          const eq = repr.k === "tagged" ? `${unionName(u)}_eq(${l}, ${r})` : equals(`(${l})`, `(${r})`, repr.k === "strings" ? types.string : repr.base)
          return expr.op === "===" ? eq : `(!${eq})`
        }
        return `(${l} ${cCompare[expr.op]} ${r})`
      })
    case "logical":
      return `(${emitExpr(expr.left)} ${expr.op} ${emitExpr(expr.right)})`
    case "unary":
      return expr.type.kind === "float" ? `(${expr.op}${emitExpr(expr.operand)})` : `((${expr.type.name})${expr.op}${emitExpr(expr.operand)})`
    case "not":
      return `(!${emitExpr(expr.operand)})`
    case "convert":
      return emitConvert(expr)
    case "call":
      return inOrder(expr.args, (args) => `${expr.func.name}(${args.join(", ")})`)
    case "builtin":
      return emitBuiltin(expr)
    case "cond":
      return `(${emitExpr(expr.cond)} ? ${emitExpr(expr.then)} : ${emitExpr(expr.else)})`
    case "concat":
      if (expr.parts.length === 0) return `ORE_STR("")`
      if (expr.parts.length === 1) return toString(expr.parts[0]!)
      return inOrder(expr.parts, (parts) => {
        const strings = parts.map((code, i) => toString(raw(code, expr.parts[i]!.type)))
        return `ore_rt_str_concat(${parts.length}, (ore_string[]){${strings.join(", ")}})`
      })
    case "index":
      return inOrder([expr.target, expr.index], ([target, index]) => {
        if (expr.target.type.kind === "string") return `ore_rt_str_at(${target}, (i64)${index})`
        return `(*(${cType(expr.type)} *)ore_rt_array_at(${target}, (i64)${index}, sizeof(${cType(expr.type)})))`
      })
    case "len":
      return expr.value.type.kind === "string" ? `(${emitExpr(expr.value)}).len` : `(${emitExpr(expr.value)})->len`
    case "slice": {
      const parts = [expr.value, ...(expr.start ? [expr.start] : []), ...(expr.end ? [expr.end] : [])]
      return inOrder(parts, ([value, start, end]) => {
        const s = start ? `(i64)${start}` : "0"
        const e = end ? `(i64)${end}` : "ORE_SLICE_END"
        if (expr.type.kind === "string") return `ore_rt_str_slice(${value}, ${s}, ${e})`
        return `ore_rt_array_slice(${value}, sizeof(${cType((expr.type as ir.ArrayType).elem)}), ${s}, ${e})`
      })
    }
    case "array": {
      const elem = cType(expr.type.elem)
      if (expr.elems.length === 0) return `ore_rt_array_new(sizeof(${elem}), 0)`
      const a = temp()
      const d = temp()
      const stores = expr.elems.map((e, i) => `${d}[${i}] = ${emitExpr(e)};`).join(" ")
      return `({ ore_array *${a} = ore_rt_array_new(sizeof(${elem}), ${expr.elems.length}); ${elem} *${d} = (${elem} *)${a}->data; ${stores} ${a}; })`
    }
    case "push": {
      // Evaluate the array and all values before appending, as JavaScript does.
      const elem = cType((expr.array.type as ir.ArrayType).elem)
      const a = temp()
      const values = expr.values.map((v) => [temp(), emitExpr(v)] as const)
      const decls = values.map(([t, v]) => `${elem} ${t} = ${v};`).join(" ")
      const pushes = values.map(([t]) => `*(${elem} *)ore_rt_array_push(${a}, sizeof(${elem})) = ${t};`).join(" ")
      return `({ ore_array *${a} = ${emitExpr(expr.array)}; ${decls} ${pushes} ${a}->len; })`
    }
    case "pop":
      return `(*(${cType(expr.type)} *)ore_rt_array_pop(${emitExpr(expr.array)}, sizeof(${cType(expr.type)})))`
    case "object": {
      const s = structName(expr.type)
      const o = temp()
      const stores = expr.fields.map((f) => `${o}->${fieldName(f.name)} = ${emitExpr(f.value)};`).join(" ")
      return `({ ${s} *${o} = ore_rt_alloc(sizeof(${s})); ${stores} ${o}; })`
    }
    case "field":
      return `(${emitExpr(expr.object)})->${fieldName(expr.name)}`
    case "alloc":
      return `((${structName(expr.type)} *)ore_rt_alloc(sizeof(${structName(expr.type)})))`
    case "method-call":
      return inOrder([expr.receiver, ...expr.args], (args) => `${expr.func.name}(${args.join(", ")})`)
    case "to-iface": {
      if (expr.itab) return `((ore_iface){(void *)${emitExpr(expr.value)}, ore_itab_${expr.itab.id}})`
      const indices = expr.indices!
      if (indices.length === 0) return `ore_rt_iface_project(${emitExpr(expr.value)}, 0, 0)`
      return `ore_rt_iface_project(${emitExpr(expr.value)}, ${indices.length}, (const i32[]){${indices.join(", ")}})`
    }
    case "iface-field":
      return `(*(${cType(expr.type)} *)ore_iface_field(${emitExpr(expr.value)}, ${expr.index}))`
    case "null":
      return inject(expr.type, expr.type.members.findIndex((m) => m.kind === "null"), "")
    case "recast":
      return recast(emitExpr(expr.value), expr.value.type, expr.type)
    case "is-null": {
      const t = temp()
      return `({ ${cType(expr.value.type)} ${t} = ${emitExpr(expr.value)}; ${isNullValue(expr.value.type as UnionType, t)}; })`
    }
    case "optional": {
      // `value?.body`: null when value is null, else body with the value bound.
      const from = expr.value.type as UnionType
      const t = temp()
      const bind = `${cType(expr.binding.type)} ${localName(expr.binding)} = ${recast(t, from, expr.binding.type)};`
      if (expr.type.kind !== "union") {
        return `({ ${cType(from)} ${t} = ${emitExpr(expr.value)}; if (!${isNullValue(from, t)}) { ${bind} ${emitExpr(expr.body)}; } })`
      }
      const r = temp()
      const none = inject(expr.type, expr.type.members.findIndex((m) => m.kind === "null"), "")
      return `({ ${cType(from)} ${t} = ${emitExpr(expr.value)}; ${cType(expr.type)} ${r}; if (${isNullValue(from, t)}) ${r} = ${none}; else { ${bind} ${r} = ${emitExpr(expr.body)}; } ${r}; })`
    }
    case "union-field": {
      const u = expr.value.type as UnionType
      const t = temp()
      const r = temp()
      const branches = u.members.map((m, i) => {
        const object = payload(u, t, i)
        let read: string
        let type: Type
        if (m.kind === "struct") {
          type = ir.findField(m, expr.name)!.type
          read = `(${object})->${fieldName(expr.name)}`
        } else {
          const index = (m as ir.InterfaceType).members.findIndex((x) => x.name === expr.name)
          type = (m as ir.InterfaceType).members[index]!.type
          read = `(*(${cType(type)} *)ore_iface_field(${object}, ${index}))`
        }
        return `if (${slotTest(u, t, i)}) ${r} = ${recast(read, type, expr.type)};`
      })
      return `({ ${cType(u)} ${t} = ${emitExpr(expr.value)}; ${cType(expr.type)} ${r}; ${branches.join(" else ")} ${r}; })`
    }
    case "typeof": {
      const from = expr.value.type
      if (from.kind !== "union") return `({ ${emitExpr(expr.value)}; ORE_STR(${stringLiteral(typeofName(from))}); })`
      const t = temp()
      const branches = from.members.map((m, i) => `${slotTest(from, t, i)} ? ORE_STR(${stringLiteral(typeofName(m))}) :`)
      return `({ ${cType(from)} ${t} = ${emitExpr(expr.value)}; ${branches.join(" ")} ORE_STR("object"); })`
    }
    case "is": {
      const t = temp()
      const value = `${cType(expr.value.type)} ${t} = ${emitExpr(expr.value)};`
      if (expr.value.type.kind === "interface") return `({ ${value} ore_iface_is(${t}, ${typeId(expr.member as ir.StructType)}); })`
      const u = expr.value.type as UnionType
      if (!expr.via) return `({ ${value} ${slotTest(u, t, memberIndex(u, expr.member))}; })`
      const i = memberIndex(u, expr.via)
      return `({ ${value} ${slotTest(u, t, i)} && ore_iface_is(${payload(u, t, i)}, ${typeId(expr.member as ir.StructType)}); })`
    }
    case "downcast": {
      const t = temp()
      const message = stringLiteral(`value is not a ${expr.type.name}`)
      return `({ ore_iface ${t} = ${emitExpr(expr.value)}; if (!ore_iface_is(${t}, ${typeId(expr.type)})) ore_rt_panic_cstr(${message}); (${cType(expr.type)})${t}.data; })`
    }
    case "coalesce": {
      const from = expr.value.type as UnionType
      const t = temp()
      return `({ ${cType(from)} ${t} = ${emitExpr(expr.value)}; ${isNullValue(from, t)} ? ${emitExpr(expr.fallback)} : ${recast(t, from, expr.type)}; })`
    }
    case "iface-call": {
      // The receiver is evaluated once, before the arguments.
      const r = temp()
      const fn = `(${cType(expr.method.result)} (*)(${["void *", ...expr.method.params.map(cType)].join(", ")}))${r}.itab[${expr.index + 1}]`
      return `({ ore_iface ${r} = ${emitExpr(expr.value)}; ${inOrder(expr.args, (args) => `(${fn})(${[`${r}.data`, ...args].join(", ")})`)}; })`
    }
  }
}

/** Prints the member a union value holds; `null` prints as `null`. */
function printUnion(u: UnionType, code: string): string {
  const t = temp()
  const branches = u.members.map((m, i) => {
    const body = m.kind === "null" ? `ore_rt_print_string(ORE_STR("null"));` : `${printCall(raw(payload(u, t, i), m))};`
    return `if (${slotTest(u, t, i)}) { ${body} }`
  })
  return `({ ${cType(u)} ${t} = ${code}; ${branches.join(" else ")} })`
}

/** Formats a printable value as a string, like `print` does. */
function toString(expr: ir.Expr): string {
  const value = emitExpr(expr)
  const t = expr.type
  if (t.kind === "union") {
    const v = temp()
    const r = temp()
    const branches = t.members.map((m, i) => {
      const body = m.kind === "null" ? `ORE_STR("null")` : toString(raw(payload(t, v, i), m))
      return `if (${slotTest(t, v, i)}) ${r} = ${body};`
    })
    return `({ ${cType(t)} ${v} = ${value}; ore_string ${r} = ORE_STR(""); ${branches.join(" else ")} ${r}; })`
  }
  if (t.kind === "literal") return value
  switch (t.kind) {
    case "string":
      return value
    case "int":
      return t.signed ? `ore_rt_str_from_i64((i64)${value})` : `ore_rt_str_from_u64((u64)${value})`
    case "float":
      return `ore_rt_str_from_${t.name}(${value})`
    case "bool":
      return `ore_rt_str_from_bool(${value})`
    default:
      throw new Error(`cannot format ${t.kind}`)
  }
}

/**
 * Declares temporaries for the parts of a place (an array and index, or an
 * object), then `before`, then a pointer `p` to the place. Returns C
 * declarations to put in a statement expression.
 */
function placePointer(target: Exclude<ir.LValue, { k: "local" }>, type: Type, p: string, before = ""): string {
  const t = cType(type)
  if (target.k === "iface-field") {
    const o = temp()
    return `ore_iface ${o} = ${emitExpr(target.value)}; ${before}${t} *${p} = ore_iface_field(${o}, ${target.index});`
  }
  if (target.k === "field") {
    const o = temp()
    return `${cType(target.object.type)} ${o} = ${emitExpr(target.object)}; ${before}${t} *${p} = &${o}->${fieldName(target.name)};`
  }
  const a = temp()
  const i = temp()
  return `ore_array *${a} = ${emitExpr(target.array)}; i64 ${i} = (i64)${emitExpr(target.index)}; ${before}${t} *${p} = ore_rt_array_at(${a}, ${i}, sizeof(${t}));`
}

function emitAssign(expr: ir.Assign): string {
  const target = expr.target
  if (target.k === "local") return `(${localName(target.local)} = ${emitExpr(expr.value)})`
  // The parts of the place and the value are evaluated before the pointer is
  // taken, since evaluating the value may grow an array.
  const t = cType(expr.type)
  const v = temp()
  const p = temp()
  const place = placePointer(target, expr.type, p, `${t} ${v} = ${emitExpr(expr.value)}; `)
  if (!expr.op) return `({ ${place} *${p} = ${v}; })`
  const current = raw(`(*${p})`, expr.type)
  const right = raw(v, expr.value.type)
  const combined: ir.Expr =
    expr.type.kind === "string"
      ? { k: "concat", type: types.string, parts: [current, right] }
      : { k: "arith", type: expr.type as ir.IntType | ir.FloatType, op: expr.op, left: current, right }
  return `({ ${place} *${p} = ${emitExpr(combined)}; })`
}

/**
 * Emits operands left to right, as Ore requires and C does not guarantee for
 * arguments and binary operators. When an operand has effects and another
 * operand is not a literal, every operand but the last is evaluated into a
 * temporary first.
 */
function inOrder(exprs: ir.Expr[], build: (codes: string[]) => string): string {
  const needsOrder = exprs.some(effects) && exprs.filter((e) => !isLiteral(e)).length >= 2
  if (!needsOrder) return build(exprs.map(emitExpr))
  const decls: string[] = []
  const codes = exprs.map((e, i) => {
    const code = emitExpr(e)
    if (i === exprs.length - 1 || isLiteral(e) || e.type.kind === "never") return code
    const t = temp()
    decls.push(`${cType(e.type)} ${t} = ${code};`)
    return t
  })
  return `({ ${decls.join(" ")} ${build(codes)}; })`
}

function isLiteral(e: ir.Expr): boolean {
  return e.k === "int" || e.k === "float" || e.k === "bool" || e.k === "string"
}

/** Whether evaluating an expression may have an observable effect, including a panic. */
function effects(e: ir.Expr): boolean {
  switch (e.k) {
    case "int":
    case "float":
    case "bool":
    case "string":
    case "local":
    case "alloc":
      return false
    case "call":
    case "method-call":
    case "builtin":
    case "assign":
    case "incdec":
    case "push":
    case "pop":
    case "index":
      return true
    case "arith":
      return e.op === "/" || e.op === "%" || e.op === "<<" || e.op === ">>" || effects(e.left) || effects(e.right)
    case "compare":
    case "logical":
      return effects(e.left) || effects(e.right)
    case "unary":
    case "not":
      return effects(e.operand)
    case "convert":
      return effects(e.value)
    case "cond":
      return effects(e.cond) || effects(e.then) || effects(e.else)
    case "concat":
      return e.parts.some(effects)
    case "len":
      return effects(e.value)
    case "slice":
      return effects(e.value) || (e.start !== undefined && effects(e.start)) || (e.end !== undefined && effects(e.end))
    case "array":
      return e.elems.some(effects)
    case "object":
      return e.fields.some((f) => effects(f.value))
    case "field":
      return effects(e.object)
    case "to-iface":
    case "iface-field":
    case "is-null":
    case "union-field":
    case "typeof":
    case "is":
      return effects(e.value)
    case "null":
      return false
    case "iface-call":
    case "downcast":
    case "recast":
    case "optional":
    case "coalesce":
      return true
  }
}

function emitArith(expr: ir.Arith): string {
  if (effects(expr.left) || effects(expr.right)) {
    return inOrder([expr.left, expr.right], ([l, r]) => emitArith({ ...expr, left: raw(l!, expr.left.type), right: raw(r!, expr.right.type) }))
  }
  const t = expr.type
  const l = emitExpr(expr.left)
  const r = emitExpr(expr.right)
  if (t.kind === "float") {
    if (expr.op === "%") return `${t.bits === 32 ? "ore_fmodf" : "ore_fmod"}(${l}, ${r})`
    return `((${t.name})(${l} ${expr.op} ${r}))`
  }
  switch (expr.op) {
    case "/":
      return `ore_div_${t.name}(${l}, ${r})`
    case "%":
      return `ore_rem_${t.name}(${l}, ${r})`
    case "<<":
    case ">>": {
      const count = expr.right.type as IntType
      const n = count.signed ? `ore_shift_count((i64)${r})` : `((u64)${r})`
      return `ore_${expr.op === "<<" ? "shl" : "shr"}_${t.name}(${l}, ${n})`
    }
    default:
      // Operands narrower than int are promoted by C; the cast wraps the result back.
      return `((${t.name})(${l} ${expr.op} ${r}))`
  }
}

function emitConvert(expr: ir.Convert): string {
  const from = expr.value.type
  const value = emitExpr(expr.value)
  if (expr.type.kind === "int" && from.kind === "float") return `ore_f2i_${expr.type.name}((f64)${value})`
  return `((${expr.type.name})${value})`
}

function emitBuiltin(expr: ir.BuiltinCall): string {
  if (expr.name === "panic") return `ore_rt_panic(${emitExpr(expr.args[0]!)})`
  const parts: string[] = []
  expr.args.forEach((arg, i) => {
    if (i > 0) parts.push("ore_rt_print_space()")
    parts.push(printCall(arg))
  })
  if (expr.name === "println") parts.push("ore_rt_print_newline()")
  return parts.length === 0 ? "((void)0)" : `(${parts.join(", ")})`
}

function printCall(arg: ir.Expr): string {
  const value = emitExpr(arg)
  const t = arg.type
  if (t.kind === "union") return printUnion(t, value)
  if (t.kind === "literal") return `ore_rt_print_string(${value})`
  switch (t.kind) {
    case "int":
      return t.signed ? `ore_rt_print_i64((i64)${value})` : `ore_rt_print_u64((u64)${value})`
    case "float":
      return `ore_rt_print_${t.name}(${value})`
    case "bool":
      return `ore_rt_print_bool(${value})`
    case "string":
      return `ore_rt_print_string(${value})`
    default:
      throw new Error(`cannot print ${t.kind}`)
  }
}

// -----------------------------------------------------------------------------
// Literals

export function intLiteral(type: IntType, value: bigint): string {
  if (value >= 0n) return `((${type.name})${value}ULL)`
  // The most negative i64 has no literal form; build every negative value from value + 1.
  return `((${type.name})(${value + 1n}LL - 1))`
}

export function floatLiteral(type: FloatType, value: number): string {
  const suffix = type.bits === 32 ? "f" : ""
  if (Number.isNaN(value)) return `((${type.name})__builtin_nan(""))`
  if (!Number.isFinite(value)) return `((${type.name})${value < 0 ? "-" : ""}__builtin_inf())`
  let text = String(value)
  if (!/[.e]/.test(text)) text += ".0"
  return `(${text}${suffix})`
}

/** A C string literal; every byte outside printable ASCII is an octal escape. */
/** What `typeof` gives for values of a type. */
function typeofName(type: Type): string {
  if (ir.isNumeric(type)) return "number"
  if (type.kind === "bool") return "boolean"
  if (isStringLike(type)) return "string"
  return "object"
}

export function stringLiteral(value: string): string {
  let out = '"'
  for (const byte of new TextEncoder().encode(value)) {
    const c = String.fromCharCode(byte)
    if (c === '"' || c === "\\") out += `\\${c}`
    else if (byte >= 0x20 && byte < 0x7f && c !== "?") out += c
    else out += `\\${byte.toString(8).padStart(3, "0")}`
  }
  return `${out}"`
}
