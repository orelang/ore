/**
 * Calls from LLVM IR into the C runtime, while the runtime is still C.
 *
 * The C ABI passes small structs by value in target-specific ways, which
 * LLVM IR does not do for us. Instead, every runtime function `f` declared in
 * `ore.h` gets a C wrapper `ore_abi_f` that takes structs (strings, closures,
 * interfaces) by pointer, returns them through a last pointer parameter, and
 * widens integers and booleans to 64 bits: a calling convention that is the
 * same in LLVM IR on every target.
 */

/** How a C parameter or result crosses the wrapper. */
export type CKind = "struct" | "int" | "double" | "float" | "ptr" | "void"

export interface CValue {
  kind: CKind
  /** The C type, for casts in the wrapper. */
  type: string
}

export interface CPrototype {
  name: string
  result: CValue
  params: CValue[]
}

const structTypes = new Set(["ore_string", "ore_closure", "ore_iface"])
const intTypes = new Set(["i8", "i16", "i32", "i64", "u8", "u16", "u32", "u64", "int", "bool", "char", "uintptr_t", "size_t"])
const pointerTypedefs = new Set(["ore_cmp_fn", "ore_hash_fn", "ore_eq_fn"])

/** Functions of the runtime not called from generated code. */
const internal = new Set(["ore_entry", "ore_rt_run_main"])

function classify(type: string): CValue {
  const t = type.replace(/\bconst\b/g, "").replace(/\s+/g, " ").trim()
  if (t === "void") return { kind: "void", type }
  if (t.includes("*") || pointerTypedefs.has(t)) return { kind: "ptr", type }
  if (structTypes.has(t)) return { kind: "struct", type: t }
  if (t === "f64" || t === "double") return { kind: "double", type: t }
  if (t === "f32" || t === "float") return { kind: "float", type: t }
  if (intTypes.has(t)) return { kind: "int", type: t }
  throw new Error(`ore.h: unsupported C type '${type}'`)
}

/** Splits a parameter list at commas outside parentheses. */
function splitParams(list: string): string[] {
  const parts: string[] = []
  let depth = 0
  let start = 0
  for (let i = 0; i < list.length; i++) {
    const c = list[i]
    if (c === "(") depth++
    else if (c === ")") depth--
    else if (c === "," && depth === 0) {
      parts.push(list.slice(start, i).trim())
      start = i + 1
    }
  }
  const last = list.slice(start).trim()
  if (last && last !== "void") parts.push(last)
  return parts
}

function param(text: string): CValue {
  // A function pointer, `void (*dispatch)(ore_select_case *)`: cast by its type without the name.
  if (text.includes("(*")) return { kind: "ptr", type: text.replace(/\(\*\s*\w+\s*\)/, "(*)") }
  const name = text.match(/(\w+)\s*$/)![1]!
  return classify(text.slice(0, text.length - name.length))
}

/** The functions declared in `ore.h`, including its static inline ones. */
export function parsePrototypes(header: string): Map<string, CPrototype> {
  const found = new Map<string, CPrototype>()
  const pattern = /^(?:static inline |_Noreturn )*([A-Za-z_][\w ]*?\**)\s*\b(ore_\w+)\(([^)]*(?:\([^)]*\)[^)]*)*)\)\s*[;{]/gm
  for (const m of header.matchAll(pattern)) {
    const name = m[2]!
    if (internal.has(name) || found.has(name)) continue
    found.set(name, { name, result: classify(m[1]!), params: splitParams(m[3]!).map(param) })
  }
  return found
}

/** The C source of the `ore_abi_*` wrappers of every runtime function. */
export function abiWrappers(header: string): string {
  const out = ["// Generated by the Ore compiler: C runtime calls for the LLVM backend.", '#include "ore.h"', ""]
  for (const p of parsePrototypes(header).values()) {
    const params: string[] = []
    const args: string[] = []
    p.params.forEach((q, i) => {
      if (q.kind === "struct") {
        params.push(`${q.type} *a${i}`)
        args.push(`*a${i}`)
      } else if (q.kind === "int") {
        params.push(`i64 a${i}`)
        args.push(`(${q.type})a${i}`)
      } else if (q.type.includes("(*)")) {
        params.push(`void *a${i}`)
        args.push(`(${q.type})a${i}`)
      } else {
        params.push(`${q.type} a${i}`)
        args.push(`a${i}`)
      }
    })
    const call = `${p.name}(${args.join(", ")})`
    const r = p.result
    if (r.kind === "struct") {
      params.push(`${r.type} *out`)
      out.push(`void ore_abi_${p.name}(${params.join(", ") || "void"}) { *out = ${call}; }`)
    } else if (r.kind === "void") {
      out.push(`void ore_abi_${p.name}(${params.join(", ") || "void"}) { ${call}; }`)
    } else {
      const type = r.kind === "int" ? "i64" : r.type
      out.push(`${type} ore_abi_${p.name}(${params.join(", ") || "void"}) { return (${type})${call}; }`)
    }
  }
  return out.join("\n") + "\n"
}
